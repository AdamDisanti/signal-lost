        private static Dictionary<string, Material> LoadMaterials()
        {
            var result = new Dictionary<string, Material>();
            foreach (string name in Parts.Select(p => p.Material).Distinct())
            {
                if (name == "HelmetGlass") { result[name] = HelmetGlass(); continue; }
                var mat = AssetDatabase.LoadAssetAtPath<Material>(MaterialFolder + "/" + name + ".mat");
                if (mat == null) throw new InvalidOperationException("Missing graybox material: " + name);
                result[name] = mat;
            }
            return result;
        }

        /// <summary>Clear, faintly blue glass that still shows his face: URP Lit, transparent alpha blend.</summary>
        private static Material HelmetGlass()
        {
            string path = Folder + "/HelmetGlass.mat";
            var mat = AssetDatabase.LoadAssetAtPath<Material>(path);
            if (mat == null)
            {
                mat = new Material(Shader.Find("Universal Render Pipeline/Lit")) { name = "HelmetGlass" };
                AssetDatabase.CreateAsset(mat, path);
            }
            mat.SetColor("_BaseColor", new Color(0.82f, 0.94f, 1f, 0.16f));
            mat.SetFloat("_Smoothness", 0.95f);
            mat.SetFloat("_Metallic", 0f);
            mat.SetFloat("_Surface", 1f); // transparent
            mat.SetFloat("_Blend", 0f);   // alpha
            mat.SetFloat("_Cull", (float)CullMode.Back);
            mat.SetFloat("_SrcBlend", (float)BlendMode.SrcAlpha);
            mat.SetFloat("_DstBlend", (float)BlendMode.OneMinusSrcAlpha);
            mat.SetFloat("_SrcBlendAlpha", (float)BlendMode.One);
            mat.SetFloat("_DstBlendAlpha", (float)BlendMode.OneMinusSrcAlpha);
            mat.SetFloat("_ZWrite", 0f);
            mat.SetOverrideTag("RenderType", "Transparent");
            mat.EnableKeyword("_SURFACE_TYPE_TRANSPARENT");
            mat.DisableKeyword("_ALPHAPREMULTIPLY_ON");
            mat.SetShaderPassEnabled("DepthOnly", false);
            mat.SetShaderPassEnabled("ShadowCaster", false);
            mat.renderQueue = (int)RenderQueue.Transparent;
            EditorUtility.SetDirty(mat);
            return mat;
        }

        // ---------- Meshes (unit primitives, flat shaded, the same shapes the preview script draws) ----------

        private static Dictionary<Prim, Mesh> BuildMeshes()
        {
            var meshes = new Dictionary<Prim, Mesh>();
            foreach (Prim prim in Enum.GetValues(typeof(Prim)))
            {
                List<Vector3[]> tris = prim switch
                {
                    Prim.Sphere1 => Icosphere(1),
                    Prim.Sphere2 => Icosphere(2),
                    Prim.Cube => Cube(),
                    Prim.Prism6 => Prism(6),
                    Prim.Prism10 => Prism(10),
                    Prim.Prism12 => Prism(12),
                    Prim.Prism16 => Prism(16),
                    Prim.Torus => Torus(0.11f),
                    _ => Torus(0.07f),
                };
                meshes[prim] = Save(Flat("Cavendish" + prim, tris));
            }
            return meshes;
        }

        private static Mesh Flat(string name, List<Vector3[]> tris)
        {
            bool ring = name.Contains("Torus");
            var vertices = new List<Vector3>();
            var normals = new List<Vector3>();
            var indices = new List<int>();
            foreach (Vector3[] t in tris)
            {
                Vector3 a = t[0], b = t[1], c = t[2];
                Vector3 centre = (a + b + c) / 3f;
                // Outward: away from the ring's core for rings, away from the middle for everything else.
                Vector3 outward = ring ? centre - new Vector3(centre.x, 0f, centre.z).normalized : centre;
                Vector3 n = Vector3.Cross(b - a, c - a);
                if (n.sqrMagnitude < 1e-12f) continue;
                // Same convention as LowPolyMesh: wound so Cross(b - a, c - a) points outward.
                if (Vector3.Dot(n, outward) < 0f) { (b, c) = (c, b); n = -n; }
                n.Normalize();
                int start = vertices.Count;
                vertices.Add(a); vertices.Add(b); vertices.Add(c);
                normals.Add(n); normals.Add(n); normals.Add(n);
                indices.Add(start); indices.Add(start + 1); indices.Add(start + 2);
            }
            var mesh = new Mesh { name = name };
            mesh.SetVertices(vertices);
            mesh.SetNormals(normals);
            mesh.SetTriangles(indices, 0);
            mesh.RecalculateBounds();
            return mesh;
        }

        private static Mesh Save(Mesh mesh)
        {
            string path = Folder + "/" + mesh.name + ".asset";
            var existing = AssetDatabase.LoadAssetAtPath<Mesh>(path);
            if (existing == null) { AssetDatabase.CreateAsset(mesh, path); return mesh; }
            EditorUtility.CopySerialized(mesh, existing);
            Object.DestroyImmediate(mesh);
            return existing;
        }

        private static List<Vector3[]> Icosphere(int subdivisions)
        {
            float t = (1f + Mathf.Sqrt(5f)) / 2f;
            var v = new List<Vector3>
            {
                new Vector3(-1, t, 0), new Vector3(1, t, 0), new Vector3(-1, -t, 0), new Vector3(1, -t, 0),
                new Vector3(0, -1, t), new Vector3(0, 1, t), new Vector3(0, -1, -t), new Vector3(0, 1, -t),
                new Vector3(t, 0, -1), new Vector3(t, 0, 1), new Vector3(-t, 0, -1), new Vector3(-t, 0, 1),
            };
            for (int i = 0; i < v.Count; i++) v[i] = v[i].normalized;
            var faces = new List<int[]>
            {
                new[] {0, 11, 5}, new[] {0, 5, 1}, new[] {0, 1, 7}, new[] {0, 7, 10}, new[] {0, 10, 11},
                new[] {1, 5, 9}, new[] {5, 11, 4}, new[] {11, 10, 2}, new[] {10, 7, 6}, new[] {7, 1, 8},
                new[] {3, 9, 4}, new[] {3, 4, 2}, new[] {3, 2, 6}, new[] {3, 6, 8}, new[] {3, 8, 9},
                new[] {4, 9, 5}, new[] {2, 4, 11}, new[] {6, 2, 10}, new[] {8, 6, 7}, new[] {9, 8, 1},
            };
            for (int s = 0; s < subdivisions; s++)
            {
                var cache = new Dictionary<long, int>();
                int Mid(int i, int j)
                {
                    long key = ((long)Mathf.Min(i, j) << 32) | (uint)Mathf.Max(i, j);
                    if (cache.TryGetValue(key, out int index)) return index;
                    v.Add(((v[i] + v[j]) * 0.5f).normalized);
                    return cache[key] = v.Count - 1;
                }
                var next = new List<int[]>();
                foreach (int[] f in faces)
                {
                    int ab = Mid(f[0], f[1]), bc = Mid(f[1], f[2]), ca = Mid(f[2], f[0]);
                    next.Add(new[] {f[0], ab, ca}); next.Add(new[] {f[1], bc, ab}); next.Add(new[] {f[2], ca, bc}); next.Add(new[] {ab, bc, ca});
                }
                faces = next;
            }
            return faces.Select(f => new[] { v[f[0]], v[f[1]], v[f[2]] }).ToList();
        }

        private static List<Vector3[]> Cube()
        {
            var tris = new List<Vector3[]>();
            for (int axis = 0; axis < 3; axis++)
                foreach (float side in new[] { -0.5f, 0.5f })
                {
                    int u = (axis + 1) % 3, w = (axis + 2) % 3;
                    var corners = new Vector3[4];
                    float[][] uv = { new[] { -0.5f, -0.5f }, new[] { 0.5f, -0.5f }, new[] { 0.5f, 0.5f }, new[] { -0.5f, 0.5f } };
                    for (int k = 0; k < 4; k++)
                    {
                        var p = Vector3.zero;
                        p[axis] = side; p[u] = uv[k][0]; p[w] = uv[k][1];
                        corners[k] = p;
                    }
                    tris.Add(new[] { corners[0], corners[1], corners[2] });
                    tris.Add(new[] { corners[0], corners[2], corners[3] });
                }
            return tris;
        }

        private static List<Vector3[]> Prism(int sides)
        {
            var tris = new List<Vector3[]>();
            var top = new Vector3(0f, 0.5f, 0f);
            var bottom = new Vector3(0f, -0.5f, 0f);
            for (int i = 0; i < sides; i++)
            {
                float a0 = 2f * Mathf.PI * i / sides, a1 = 2f * Mathf.PI * (i + 1) / sides;
                var p0 = new Vector3(Mathf.Cos(a0), 0f, Mathf.Sin(a0));
                var p1 = new Vector3(Mathf.Cos(a1), 0f, Mathf.Sin(a1));
                tris.Add(new[] { p0 + bottom, p1 + bottom, p1 + top });
                tris.Add(new[] { p0 + bottom, p1 + top, p0 + top });
                tris.Add(new[] { top, p0 + top, p1 + top });
                tris.Add(new[] { bottom, p1 + bottom, p0 + bottom });
            }
            return tris;
        }

        private static List<Vector3[]> Torus(float minor, int majorSegments = 16, int minorSegments = 6)
        {
            var tris = new List<Vector3[]>();
            Vector3 P(int i, int j)
            {
                float u = 2f * Mathf.PI * i / majorSegments, v = 2f * Mathf.PI * j / minorSegments;
                float r = 1f + minor * Mathf.Cos(v);
                return new Vector3(r * Mathf.Cos(u), minor * Mathf.Sin(v), r * Mathf.Sin(u));
            }
            for (int i = 0; i < majorSegments; i++)
                for (int j = 0; j < minorSegments; j++)
                {
                    Vector3 a = P(i, j), b = P(i + 1, j), c = P(i + 1, j + 1), d = P(i, j + 1);
                    tris.Add(new[] { a, b, c });
                    tris.Add(new[] { a, c, d });
                }
            return tris;
        }

        private static void EnsureFolder(string path)
        {
            if (AssetDatabase.IsValidFolder(path)) return;
            int slash = path.LastIndexOf('/');
            AssetDatabase.CreateFolder(path.Substring(0, slash), path.Substring(slash + 1));
        }
