        [MenuItem("Signal Lost/Characters/Rebuild Cavendish Model")]
        public static void Rebuild()
        {
            if (EditorApplication.isPlayingOrWillChangePlaymode)
            {
                EditorUtility.DisplayDialog("Stop Play mode first", "Press Stop, then run this again.", "OK");
                return;
            }
            if (!Application.isBatchMode && !EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo()) return;
            string returnTo = SceneManager.GetActiveScene().path;

            // Scenes save how far his old Visual was lowered (seated). Remember it, since Visual is replaced.
            var seated = RecordSeatedHeights();

            EnsureFolder(Folder);
            var meshes = BuildMeshes();
            var materials = LoadMaterials();

            GameObject root = PrefabUtility.LoadPrefabContents(PrefabPath);
            try
            {
                Transform old = root.transform.Find("Visual");
                if (old != null) Object.DestroyImmediate(old.gameObject);
                BuildVisual(root.transform, meshes, materials);

                var capsule = root.GetComponent<CapsuleCollider>();
                if (capsule == null) capsule = root.AddComponent<CapsuleCollider>();
                capsule.direction = 2; // along his length
                capsule.center = new Vector3(0f, 0.68f, 0.18f);
                capsule.radius = 0.44f;
                capsule.height = 1.9f;
                Transform anchor = root.transform.Find("DialogueAnchor");
                if (anchor != null) anchor.localPosition = DialogueHeight;
                PrefabUtility.SaveAsPrefabAsset(root, PrefabPath);
            }
            finally { PrefabUtility.UnloadPrefabContents(root); }
            AssetDatabase.SaveAssets();

            UpdateScenes(seated);
            if (!string.IsNullOrEmpty(returnTo) && File.Exists(returnTo)) EditorSceneManager.OpenScene(returnTo);
            Debug.Log($"CAVENDISH_MODEL_REBUILT: {Parts.Length} parts; {seated.Count} seated Cavendish(es) carried over.");
        }

        private static void BuildVisual(Transform root, Dictionary<Prim, Mesh> meshes, Dictionary<string, Material> materials)
        {
            var visual = new GameObject("Visual").transform;
            visual.SetParent(root, false);
            var body = new GameObject("Body").transform;
            body.SetParent(visual, false);

            var parents = new Dictionary<string, Transform> { ["Body"] = body };
            foreach (Group group in Groups)
            {
                var pivot = new GameObject(group.Name).transform;
                pivot.SetParent(body, false);
                pivot.localPosition = group.Position;
                parents[group.Name] = pivot;
            }
            foreach (Part part in Parts)
            {
                var go = new GameObject(part.Name);
                go.transform.SetParent(parents[part.Parent], false);
                go.transform.localPosition = part.Position;
                go.transform.localRotation = part.Rotation;
                go.transform.localScale = part.Scale;
                go.AddComponent<MeshFilter>().sharedMesh = meshes[part.Prim];
                var renderer = go.AddComponent<MeshRenderer>();
                renderer.sharedMaterial = materials[part.Material];
                renderer.shadowCastingMode = part.Material == "HelmetGlass" ? ShadowCastingMode.Off : ShadowCastingMode.On;
            }

            var pose = visual.gameObject.AddComponent<CavendishPose>();
            var data = new SerializedObject(pose);
            data.FindProperty("body").objectReferenceValue = body;
            SetArray(data.FindProperty("frontLegs"), parents["Front Right Leg"], parents["Front Left Leg"]);
            SetArray(data.FindProperty("hindLegs"), parents["Hind Right Leg"], parents["Hind Left Leg"]);
            data.ApplyModifiedPropertiesWithoutUndo();
        }

        private static void SetArray(SerializedProperty property, params Transform[] items)
        {
            property.arraySize = items.Length;
            for (int i = 0; i < items.Length; i++) property.GetArrayElementAtIndex(i).objectReferenceValue = items[i];
        }

        // ---------- Seated heights in scenes ----------

        private readonly struct Seated
        {
            public readonly string Scene, Path; public readonly float Height;
            public Seated(string scene, string path, float height) { Scene = scene; Path = path; Height = height; }
        }

        private static IEnumerable<string> ScenesUsingPrefab()
        {
            string guid = AssetDatabase.AssetPathToGUID(PrefabPath);
            foreach (string id in AssetDatabase.FindAssets("t:Scene", new[] { "Assets" }))
            {
                string path = AssetDatabase.GUIDToAssetPath(id);
                if (File.Exists(path) && File.ReadAllText(path).Contains(guid)) yield return path;
            }
        }

        private static IEnumerable<GameObject> Instances(Scene scene)
        {
            foreach (GameObject top in scene.GetRootGameObjects())
                foreach (Transform t in top.GetComponentsInChildren<Transform>(true))
                    if (PrefabUtility.IsOutermostPrefabInstanceRoot(t.gameObject) &&
                        PrefabUtility.GetPrefabAssetPathOfNearestInstanceRoot(t.gameObject) == PrefabPath)
                        yield return t.gameObject;
        }

        private static string PathOf(Transform t) => t.parent == null ? t.name : PathOf(t.parent) + "/" + t.name;

        private static List<Seated> RecordSeatedHeights()
        {
            var found = new List<Seated>();
            foreach (string path in ScenesUsingPrefab())
            {
                Scene scene = EditorSceneManager.OpenScene(path, OpenSceneMode.Single);
                foreach (GameObject cavendish in Instances(scene))
                {
                    Transform visual = cavendish.transform.Find("Visual");
                    if (visual != null && Mathf.Abs(visual.localPosition.y) > 0.001f)
                        found.Add(new Seated(path, PathOf(cavendish.transform), visual.localPosition.y));
                }
            }
            return found;
        }

        /// <summary>
        /// In every scene with him: puts back his seated height (his Visual is new, so the scene's old value no longer
        /// applies) and lowers his speech-bubble anchor to the new, shorter model.
        /// </summary>
        private static void UpdateScenes(List<Seated> seated)
        {
            foreach (string path in ScenesUsingPrefab())
            {
                Scene scene = EditorSceneManager.OpenScene(path, OpenSceneMode.Single);
                foreach (GameObject cavendish in Instances(scene))
                {
                    string at = PathOf(cavendish.transform);
                    Transform visual = cavendish.transform.Find("Visual");
                    foreach (Seated s in seated)
                        if (s.Scene == path && s.Path == at && visual != null)
                            visual.localPosition = new Vector3(visual.localPosition.x, s.Height, visual.localPosition.z);
                    Transform voice = cavendish.transform.Find("Cavendish Dialogue");
                    if (voice != null) voice.localPosition = DialogueHeight;
                }
                EditorSceneManager.MarkSceneDirty(scene);
                EditorSceneManager.SaveScene(scene);
            }
        }

